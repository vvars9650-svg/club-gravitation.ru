const assert=require('node:assert/strict'),fs=require('node:fs');
const a=require('../assets/js/apply');
const html=fs.readFileSync('apply/index.html','utf8');
assert.equal(a.FORM_VERSION,'FORM-2.3');
for(const field of a.FORM_FIELDS) assert.ok(html.includes('name="'+field+'"'),field);
for(const field of ['occupation','life_outside_work','desired_connections','acquaintance_methods','source','public_profile_url']) assert.ok(!html.includes('name="'+field+'"'),field);
assert.equal((html.match(/class="consent"/g)||[]).length,2);
assert.ok(!/\schecked(?:\s|>)/.test(html));
assert.ok(!html.includes('data-step='));
assert.ok(html.includes('Как с вами лучше связаться? *'));
assert.ok(html.includes('Укажите мессенджер или контакт'));
assert.ok(html.includes('Добавьте одну актуальную фотографию, на которой вас хорошо видно.'));
assert.ok(html.includes('Все поля со звёздочкой обязательны.'));
console.log('V5 short form static contract tests passed');
